"""Compare KGW vs SynthID watermark detectability/FPR across truncation
lengths, from pre-generated corpora JSONL files. RUNS LOCALLY ONLY (needs a
real HF tokenizer + vllm_watermark.{kgw,synthid} detectors -- same
constraint as benchmarks/analyze_detection.py; transformers/torch are not
installed in the bench pod).

What this does
--------------
For each of --kgw-corpus / --synthid-corpus / --unwatermarked-corpus /
--human-corpus (each optional -- see "Missing corpora" below), tokenizes
every row's `"text"` field with --model-tokenizer, TRUNCATES the token id
sequence to each of 200/256/512 tokens (dropping rows shorter than that
truncation length -- there is nothing to truncate down to), and scores the
truncated token ids with:
  - KGW  (vllm_watermark.kgw.detector.score_token_ids / DEFAULT_Z_THRESHOLD)
  - SynthID mean scorer (vllm_watermark.synthid.detector.score_token_ids_mean)
using the SAME key material (via vllm_watermark.keys.load_key(key_id=...))
that generation used.

Detectability: TPR at the scheme's own detection threshold --
z>=4.0 (DEFAULT_Z_THRESHOLD) for KGW, scored against --kgw-corpus;
z>=4.0 (vllm_watermark.synthid.detector.DEFAULT_Z_THRESHOLD -- see that
module's docstring "Not ported from either source" for the derivation of
this threshold convention) for SynthID, scored against --synthid-corpus.
FPR: the same two detectors run against --unwatermarked-corpus and
--human-corpus (each reported as its own row -- pooling them would hide a
systematic difference between "not watermarked, same model" and "not
generated by the model at all").

Missing corpora
----------------
Any of the four --*-corpus flags may be omitted. A missing corpus produces
a clear "not present" row/cell in both the markdown table and the JSON
output -- this script never crashes because one input file doesn't exist
yet (e.g. SynthID generation hasn't been run against the cluster). This is
also what the --self-test / synthetic-fixture execution path below relies
on: it exercises the "not present" branch for whichever corpora it doesn't
supply.

Usage:
    python3 benchmarks/compare_schemes.py \\
        --kgw-corpus benchmarks/data/corpus_kgw.jsonl \\
        --synthid-corpus benchmarks/data/corpus_synthid.jsonl \\
        --unwatermarked-corpus benchmarks/data/corpus_unwatermarked.jsonl \\
        --human-corpus benchmarks/data/human_corpus.jsonl \\
        --model-tokenizer Qwen/Qwen2.5-0.5B-Instruct \\
        --key-id default \\
        --out benchmarks/data/scheme_comparison.md

The watermark key is loaded via vllm_watermark.keys.load_key(), same as
analyze_detection.py -- never passed on the command line, never printed.
"""

from __future__ import annotations

import argparse
import json
import statistics
import sys
from pathlib import Path

TRUNCATION_LENGTHS = (200, 256, 512)

NOT_PRESENT = "not present"


def _ensure_vllm_watermark_importable() -> str:
    try:
        import vllm_watermark

        return f"already importable ({vllm_watermark.__file__})"
    except ImportError:
        pass

    src_dir = Path(__file__).resolve().parent.parent / "src"
    sys.path.insert(0, str(src_dir))
    try:
        import vllm_watermark

        return f"sys.path fallback -> {src_dir} ({vllm_watermark.__file__})"
    except ImportError as exc:
        print(
            f"error: could not import vllm_watermark, even after adding {src_dir} "
            f"to sys.path: {exc}",
            file=sys.stderr,
        )
        raise SystemExit(2) from exc


_IMPORT_NOTE = _ensure_vllm_watermark_importable()


def load_jsonl_rows(path: str) -> "list[dict]":
    rows = []
    with open(path, encoding="utf-8") as f:
        for line_num, line in enumerate(f, start=1):
            line = line.strip()
            if not line:
                continue
            try:
                rows.append(json.loads(line))
            except json.JSONDecodeError as exc:
                print(f"  warning: {path}:{line_num}: malformed JSON, skipping row: {exc}", file=sys.stderr)
    return rows


def _fmt(x, digits=3):
    return "n/a" if x is None else f"{x:.{digits}f}"


def score_corpus_at_lengths(
    path: str,
    tokenizer,
    score_token_ids_fn,
    truncation_lengths: "tuple[int, ...]",
) -> "dict[int, dict]":
    """Tokenize every row's text once, then for each truncation length in
    truncation_lengths: keep rows with >= that many tokens, truncate to
    exactly that many, score with score_token_ids_fn(token_ids) ->
    an object with .z_score/.prediction (raises ValueError if unscoreable),
    and summarize (n, mean_z, rate-at-threshold via .prediction).

    Returns {length: {"n": int, "mean_z": float|None, "rate": float|None,
                       "n_skipped_too_short": int, "n_skipped_score_error": int}}.
    """
    raw_rows = load_jsonl_rows(path)
    tokenized = []
    for row in raw_rows:
        text = row.get("text")
        if not text or not isinstance(text, str):
            continue
        tokenized.append(tokenizer.encode(text, add_special_tokens=False))

    out: "dict[int, dict]" = {}
    for length in truncation_lengths:
        z_values = []
        n_pos = 0
        n_skipped_too_short = 0
        n_skipped_score_error = 0
        n_total = 0
        for token_ids in tokenized:
            if len(token_ids) < length:
                n_skipped_too_short += 1
                continue
            truncated = token_ids[:length]
            try:
                result = score_token_ids_fn(truncated)
            except ValueError:
                n_skipped_score_error += 1
                continue
            n_total += 1
            z_values.append(result.z_score)
            if result.prediction:
                n_pos += 1
        out[length] = {
            "n": n_total,
            "mean_z": statistics.mean(z_values) if z_values else None,
            "rate": (n_pos / n_total) if n_total else None,
            "n_skipped_too_short": n_skipped_too_short,
            "n_skipped_score_error": n_skipped_score_error,
        }
    return out


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--kgw-corpus", default=None, help="JSONL corpus of KGW-watermarked completions")
    parser.add_argument("--synthid-corpus", default=None, help="JSONL corpus of SynthID-watermarked completions")
    parser.add_argument("--unwatermarked-corpus", default=None, help="JSONL corpus of unwatermarked model completions")
    parser.add_argument("--human-corpus", default=None, help="JSONL corpus of human-authored text")
    parser.add_argument("--model-tokenizer", default="Qwen/Qwen2.5-0.5B-Instruct")
    parser.add_argument("--key-id", default=None, help="watermark key id (default: WATERMARK_KEY_ID env or 'default')")
    parser.add_argument("--gamma", type=float, default=0.25, help="KGW gamma, must match generation time")
    parser.add_argument(
        "--synthid-depth",
        type=int,
        default=None,
        help="SynthID tournament depth (default: vllm_watermark.synthid.core.DEFAULT_SYNTHID_DEPTH)",
    )
    parser.add_argument("--synthid-ngram-len", type=int, default=5, help="SynthID ngram_len, must match generation time")
    parser.add_argument(
        "--self-test",
        action="store_true",
        help=(
            "run against a tiny synthetic in-memory fixture with a fake trivial scorer instead of real "
            "corpora/detectors -- proves the plumbing (truncation, missing-corpus handling, table "
            "rendering) without needing transformers/torch or real watermarked text"
        ),
    )
    parser.add_argument("--out", default="scheme_comparison.md", help="output markdown path; a sibling .json is also written")
    return parser


def _run_self_test(args: argparse.ArgumentParser) -> int:
    """Exercise the truncation/missing-corpus/table-rendering plumbing with
    a fake trivial tokenizer+scorer, no transformers/torch/real corpora
    required. See --self-test help."""
    import tempfile

    class FakeTokenizer:
        def encode(self, text, add_special_tokens=False):
            # one "token" per whitespace-separated word -- deterministic,
            # dependency-free, plenty of "tokens" for length-200/256/512
            # truncation once the fixture text is repeated.
            return text.split()

    class FakeResult:
        def __init__(self, z_score, prediction):
            self.z_score = z_score
            self.prediction = prediction

    def fake_watermarked_scorer(token_ids):
        # deterministic "detects" pattern: higher z the longer the run,
        # always predicts True -- stands in for a real detector well
        # enough to prove the length-bucketing/reporting code paths.
        return FakeResult(z_score=5.0 + 0.001 * len(token_ids), prediction=True)

    def fake_unwatermarked_scorer(token_ids):
        return FakeResult(z_score=0.1, prediction=False)

    tmpdir = Path(tempfile.mkdtemp(prefix="compare_schemes_selftest_"))
    kgw_path = tmpdir / "kgw.jsonl"
    unwm_path = tmpdir / "unwm.jsonl"
    word = "lorem "
    with open(kgw_path, "w", encoding="utf-8") as f:
        for _ in range(5):
            f.write(json.dumps({"text": word * 600}) + "\n")
    with open(unwm_path, "w", encoding="utf-8") as f:
        for _ in range(5):
            f.write(json.dumps({"text": word * 600}) + "\n")

    tokenizer = FakeTokenizer()

    # Two DISTINGUISHABLE fake detectors so the six-row model is actually
    # proven: the same control corpus must appear once per detector with
    # that detector's own signature z value (audit fix 2026-08-08).
    def fake_kgw_det(token_ids):
        return FakeResult(z_score=0.1, prediction=False)

    def fake_synthid_det(token_ids):
        return FakeResult(z_score=0.2, prediction=False)

    results = {}
    results["kgw"] = score_corpus_at_lengths(str(kgw_path), tokenizer, fake_watermarked_scorer, TRUNCATION_LENGTHS)
    results["synthid"] = None  # deliberately absent -> "not present" row
    for det_name, scorer in [("kgw det", fake_kgw_det), ("synthid det", fake_synthid_det)]:
        results[f"unwatermarked ({det_name})"] = score_corpus_at_lengths(
            str(unwm_path), tokenizer, scorer, TRUNCATION_LENGTHS)
    results["human (kgw det)"] = None
    results["human (synthid det)"] = None
    for label, per in results.items():
        print(f"[self-test] {label}: {NOT_PRESENT if per is None else 'scored'}")

    md_path, json_path = render_report(
        {"self_test": True, "note": "synthetic fixture, not real corpora/detectors"}, results, args.out
    )
    print(f"[self-test] wrote {md_path}")
    print(f"[self-test] wrote {json_path}")

    assert results["kgw"] is not None and results["kgw"][200]["n"] == 5, "self-test: kgw@200 should have n=5"
    assert results["synthid"] is None, "self-test: synthid corpus should be absent"
    assert results["human (kgw det)"] is None, "self-test: absent human corpus -> not-present per detector"
    assert results["human (synthid det)"] is None
    assert results["synthid"] is None, "self-test: absent synthid corpus -> not-present"
    for length in TRUNCATION_LENGTHS:  # all three lengths (200/256/512)
        a = results["unwatermarked (kgw det)"][length]
        b = results["unwatermarked (synthid det)"][length]
        assert a["rate"] == 0.0 and b["rate"] == 0.0, "self-test: control scorers never predict True"
        assert abs(a["mean_z"] - 0.1) < 1e-9 and abs(b["mean_z"] - 0.2) < 1e-9, (
            "self-test: same control corpus must be scored by BOTH detectors, "
            "each with its own signature z (proves six-row routing)")
    print("[self-test] all assertions passed")
    return 0


def render_report(config_summary: dict, results: "dict[str, dict | None]", out: str) -> "tuple[str, str]":
    """results: {label: {length: {n, mean_z, rate, ...}} | None (not present)}.
    Labels: "kgw" / "synthid" (watermarked corpora, rate = TPR, scored with
    that scheme's own detector) and "unwatermarked (kgw det)" /
    "unwatermarked (synthid det)" / "human (kgw det)" / "human (synthid det)"
    (control corpora, rate = FPR of the NAMED detector — one row per
    (corpus, detector) pair so each scheme's FPR is independently supported;
    audit fix 2026-08-08)."""
    out_stem = out[:-3] if out.endswith(".md") else out
    md_path = f"{out_stem}.md"
    json_path = f"{out_stem}.json"

    Path(md_path).parent.mkdir(parents=True, exist_ok=True)
    Path(json_path).parent.mkdir(parents=True, exist_ok=True)

    with open(json_path, "w", encoding="utf-8") as f:
        json.dump({"config": config_summary, "results": results}, f, indent=2)

    def rate_label(label: str) -> str:
        return "TPR" if label in ("kgw", "synthid") else "FPR"

    md_lines = ["# KGW vs SynthID scheme comparison", ""]
    md_lines.append(" ".join(f"{k}=`{v}`" for k, v in config_summary.items()))
    md_lines.append("")

    for length in TRUNCATION_LENGTHS:
        md_lines.append(f"## Truncation length {length} tokens")
        md_lines.append("")
        md_lines.append("| corpus | n | mean z | rate | metric |")
        md_lines.append("|---|---|---|---|---|")
        for label, per_length in results.items():
            if per_length is None:
                md_lines.append(f"| {label} | {NOT_PRESENT} | {NOT_PRESENT} | {NOT_PRESENT} | {rate_label(label)} |")
                continue
            stats = per_length[length]
            md_lines.append(
                f"| {label} | {stats['n']} | {_fmt(stats['mean_z'])} | {_fmt(stats['rate'])} | {rate_label(label)} |"
            )
        md_lines.append("")

    md_lines.append("## Notes")
    md_lines.append("")
    md_lines.append(
        "- `kgw`/`synthid` rows: TPR at that scheme's own detection threshold, scored with that scheme's own detector."
    )
    md_lines.append(
        "- `unwatermarked (...)` / `human (...)` rows: FPR of the named detector on that control corpus -- "
        "one row per (corpus, detector) pair, so each scheme's FPR is independently supported."
    )
    md_lines.append(
        "- n varies by truncation length: a row is scored at length L only if it has >= L scored tokens "
        "(shorter completions are excluded, counted in n_skipped_too_short in the JSON). Control corpora "
        "generated/chunked at ~256 tokens therefore have n=0 at the 512 row unless a 512-token control "
        "corpus is supplied."
    )
    md_lines.append(f"- `{NOT_PRESENT}` cells mean that --*-corpus flag was omitted, not a scoring failure.")
    md_lines.append("")

    with open(md_path, "w", encoding="utf-8") as f:
        f.write("\n".join(md_lines) + "\n")

    return md_path, json_path


def main(argv: "list[str] | None" = None) -> int:
    args = build_parser().parse_args(argv)
    print(f"vllm_watermark import: {_IMPORT_NOTE}")

    if args.self_test:
        return _run_self_test(args)

    try:
        from transformers import AutoConfig, AutoTokenizer
    except ImportError as exc:
        print(f"error: this script requires transformers (local-only tool): {exc}", file=sys.stderr)
        return 2

    from vllm_watermark.keys import load_key
    from vllm_watermark.kgw.core import KGWConfig
    from vllm_watermark.kgw.detector import score_token_ids as kgw_score_token_ids

    try:
        key = load_key(key_id=args.key_id)
    except (RuntimeError, KeyError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    print(f"Loading tokenizer/config {args.model_tokenizer!r} ...")
    tokenizer = AutoTokenizer.from_pretrained(args.model_tokenizer)
    vocab_size = AutoConfig.from_pretrained(args.model_tokenizer).vocab_size

    kgw_cfg = KGWConfig(vocab_size=vocab_size, hash_key=key.hash_key, gamma=args.gamma)

    def kgw_scorer(token_ids):
        return kgw_score_token_ids(token_ids, kgw_cfg, ignore_repeated_ngrams=True)

    synthid_scorer = None
    synthid_import_error = None
    try:
        from vllm_watermark.synthid.core import DEFAULT_SYNTHID_DEPTH, SYNTHID_KEY_LABEL, SynthIDConfig
        from vllm_watermark.synthid.detector import score_token_ids_mean

        if args.synthid_depth is not None and args.synthid_depth <= 0:
            print(f"error: --synthid-depth must be a positive integer, got {args.synthid_depth}", file=sys.stderr)
            return 2
        if args.synthid_ngram_len < 1:
            # canonical bound: SynthIDConfig.__post_init__ accepts ngram_len >= 1
            print(f"error: --synthid-ngram-len must be >= 1, got {args.synthid_ngram_len}", file=sys.stderr)
            return 2
        depth = args.synthid_depth or DEFAULT_SYNTHID_DEPTH
        synthid_keys = key.derive_subkeys(depth, SYNTHID_KEY_LABEL)
        synthid_cfg = SynthIDConfig(vocab_size=vocab_size, keys=synthid_keys, ngram_len=args.synthid_ngram_len)

        def synthid_scorer(token_ids, _cfg=synthid_cfg):
            return score_token_ids_mean(token_ids, _cfg)

    except ImportError as exc:
        synthid_import_error = str(exc)
        print(f"warning: vllm_watermark.synthid not importable ({exc}); synthid rows will be 'not present'", file=sys.stderr)

    results: "dict[str, dict | None]" = {}

    if args.kgw_corpus:
        print(f"Scoring kgw corpus <- {args.kgw_corpus} (KGW detector)")
        results["kgw"] = score_corpus_at_lengths(args.kgw_corpus, tokenizer, kgw_scorer, TRUNCATION_LENGTHS)
    else:
        results["kgw"] = None

    if args.synthid_corpus and synthid_scorer is not None:
        print(f"Scoring synthid corpus <- {args.synthid_corpus} (SynthID mean detector)")
        results["synthid"] = score_corpus_at_lengths(args.synthid_corpus, tokenizer, synthid_scorer, TRUNCATION_LENGTHS)
    elif args.synthid_corpus and synthid_scorer is None:
        print(f"warning: --synthid-corpus given but synthid detector unavailable ({synthid_import_error}); reporting 'not present'", file=sys.stderr)
        results["synthid"] = None
    else:
        results["synthid"] = None

    # unwatermarked/human FPR: scored with EVERY available detector, one
    # self-describing row per (corpus, detector) pair. A single pooled row
    # scored by one detector cannot support a per-scheme FPR claim (audit
    # finding, 2026-08-08) -- each scheme's FPR needs its own detector run.
    fpr_scorers = [("kgw det", kgw_scorer)]
    if synthid_scorer is not None:
        fpr_scorers.append(("synthid det", synthid_scorer))

    if args.unwatermarked_corpus:
        for det_name, scorer in fpr_scorers:
            print(f"Scoring unwatermarked corpus <- {args.unwatermarked_corpus} (FPR, {det_name})")
            results[f"unwatermarked ({det_name})"] = score_corpus_at_lengths(
                args.unwatermarked_corpus, tokenizer, scorer, TRUNCATION_LENGTHS)
        if synthid_scorer is None:
            # Explicit, not silent: corpus supplied but synthid detector
            # unavailable -> render a visible not-present row (audit fix).
            results["unwatermarked (synthid det)"] = None
    else:
        results["unwatermarked (kgw det)"] = None
        results["unwatermarked (synthid det)"] = None

    if args.human_corpus:
        for det_name, scorer in fpr_scorers:
            print(f"Scoring human corpus <- {args.human_corpus} (FPR, {det_name})")
            results[f"human ({det_name})"] = score_corpus_at_lengths(
                args.human_corpus, tokenizer, scorer, TRUNCATION_LENGTHS)
        if synthid_scorer is None:
            results["human (synthid det)"] = None
    else:
        results["human (kgw det)"] = None
        results["human (synthid det)"] = None

    config_summary = {
        "model_tokenizer": args.model_tokenizer,
        "vocab_size": vocab_size,
        "key_id": key.key_id,
        "gamma": args.gamma,
        "synthid_depth": (synthid_cfg.keys and len(synthid_cfg.keys)) if synthid_scorer is not None else "unavailable",
        "synthid_ngram_len": args.synthid_ngram_len,
        "truncation_lengths": list(TRUNCATION_LENGTHS),
    }
    md_path, json_path = render_report(config_summary, results, args.out)
    print(f"wrote {md_path}")
    print(f"wrote {json_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
